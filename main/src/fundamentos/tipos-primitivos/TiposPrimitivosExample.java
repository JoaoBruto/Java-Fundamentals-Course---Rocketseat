public class TiposPrimitivosExample {
    public static void main(String[] args) {
        byte idade = 25;
        short quantidade = 300;
        int populacao = 2147483647;
        long distancia = 9223372036854775807L;
        float altura = 1.75f;
        double preco = 19.90;
        char inicial = 'J';
        boolean estudante = true;

        System.out.println("byte: " + idade);
        System.out.println("short: " + quantidade);
        System.out.println("int: " + populacao);
        System.out.println("long: " + distancia);
        System.out.println("float: " + altura);
        System.out.println("double: " + preco);
        System.out.println("char: " + inicial);
        System.out.println("boolean: " + estudante);
    }
}
